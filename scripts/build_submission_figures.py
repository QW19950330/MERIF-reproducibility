#!/usr/bin/env python3
"""Build the figures used by the current MERIF revision from frozen plot data.

Figures 1-4 are editable workflow diagrams and are copied from the submitted
reference renders. Figures 5-16 are regenerated by the latest complete V6
Matplotlib renderer. The mapping reflects the final manuscript, which moved
the V6 RCQR window-sensitivity figure to the supplement.
"""

from __future__ import annotations

import argparse
import importlib.util
import shutil
import tempfile
from pathlib import Path


ROOT = Path(__file__).resolve().parents[1]
V6_DIR = ROOT / "FINAL_FIGURES4PAPERS_EDITORIAL_V6"
REFERENCE_DIR = ROOT / "reference" / "submitted_main_figures"

# Submitted manuscript number -> last complete executable V6 figure code.
MAIN_FIGURE_MAP = {
    5: "Fig05",
    6: "Fig06",
    7: "Fig07",
    8: "Fig08",
    9: "Fig10",
    10: "Fig11",
    11: "Fig12",
    12: "Fig13",
    13: "Fig14",
    14: "Fig15",
    15: "Fig16",
    16: "Fig17",
}


def load_renderer():
    path = V6_DIR / "make_v6_editorial_figures.py"
    spec = importlib.util.spec_from_file_location("merif_v6_renderer", path)
    if spec is None or spec.loader is None:
        raise RuntimeError(f"Cannot load renderer: {path}")
    module = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(module)
    return module


def build_one(module, submitted_number: int, output_dir: Path) -> list[Path]:
    output_dir.mkdir(parents=True, exist_ok=True)
    stem = f"Figure_{submitted_number:02d}"

    if submitted_number <= 4:
        source = REFERENCE_DIR / f"{stem}.png"
        destination = output_dir / f"{stem}.png"
        shutil.copy2(source, destination)
        return [destination]

    code = MAIN_FIGURE_MAP[submitted_number]
    source_table = V6_DIR / code / f"{code.upper()}_SOURCE_TABLE.csv"

    # Render in a temporary tree so tracked reference artifacts remain unchanged.
    with tempfile.TemporaryDirectory(prefix="merif_figure_") as tmp:
        temp_root = Path(tmp)
        temp_figure_dir = temp_root / code
        temp_figure_dir.mkdir(parents=True)
        shutil.copy2(source_table, temp_figure_dir / source_table.name)

        original_out = module.OUT
        module.OUT = temp_root
        try:
            module.render_one(code, stage="final")
        finally:
            module.OUT = original_out

        outputs = []
        for suffix in (".png", ".pdf", ".svg"):
            source = temp_figure_dir / f"{code.upper()}{suffix}"
            destination = output_dir / f"{stem}{suffix}"
            shutil.copy2(source, destination)
            outputs.append(destination)
        return outputs


def parse_args() -> argparse.Namespace:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "--output-dir",
        type=Path,
        default=ROOT / "outputs" / "submission_figures",
        help="Destination directory (default: outputs/submission_figures)",
    )
    parser.add_argument(
        "--figure",
        type=int,
        action="append",
        choices=range(1, 17),
        help="Build one figure number; repeat to build several. Default: all 16.",
    )
    return parser.parse_args()


def main() -> None:
    args = parse_args()
    requested = sorted(set(args.figure or range(1, 17)))
    module = load_renderer()
    generated: list[Path] = []
    for number in requested:
        print(f"Building Figure {number:02d}...")
        generated.extend(build_one(module, number, args.output_dir.resolve()))
    print(f"Generated {len(generated)} files in {args.output_dir.resolve()}")


if __name__ == "__main__":
    main()
